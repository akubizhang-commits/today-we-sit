const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const modules=new Map();
function collect(file){
  const id=path.relative(root,file).split(path.sep).join('/');
  if(modules.has(id))return id;
  const source=fs.readFileSync(file,'utf8');modules.set(id,'');
  const compiled=source.replace(/require\((['"])(\.[^'"]*)\1\)/g,(_,quote,request)=>{
    const dep=path.resolve(path.dirname(file),request.endsWith('.js')?request:request+'.js');
    if(!dep.startsWith(root+path.sep))throw new Error('Dependency outside project');
    return `require(${JSON.stringify(collect(dep))})`;
  });
  modules.set(id,compiled);return id;
}
const entry=collect(path.join(root,'web/entry.js'));
const bundle=`/* Generated by npm run build; edit src/, not this file. */\n(function(){\n'use strict';\nconst modules={\n${[...modules].map(([id,src])=>`${JSON.stringify(id)}:function(module,exports,require){\n${src}\n}`).join(',\n')}\n};\nconst cache={};function require(id){if(cache[id])return cache[id].exports;const module={exports:{}};cache[id]=module;if(!modules[id])throw new Error('Module missing: '+id);modules[id](module,module.exports,require);return module.exports;}require(${JSON.stringify(entry)});\n})();`;
fs.writeFileSync(path.join(root,'web/game.bundle.js'),bundle);
const dest=path.join(root,'dist/wechat');
fs.mkdirSync(dest,{recursive:true});
for(const name of ['game.js','game.json','project.config.json'])fs.copyFileSync(path.join(root,name),path.join(dest,name));
fs.cpSync(path.join(root,'src'),path.join(dest,'src'),{recursive:true});
console.log(`Browser bundle: ${modules.size} modules, ${(Buffer.byteLength(bundle)/1024).toFixed(1)} KiB`);
console.log('WeChat project: dist/wechat (touristappid; replace with your own AppID for device preview)');
