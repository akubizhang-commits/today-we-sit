'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {readContent,validateContent}=require('./validate-content');
const pick=(value,keys)=>Object.fromEntries(keys.filter(k=>Object.hasOwn(value,k)).map(k=>[k,value[k]]));
function buildContent({root=path.resolve(__dirname,'..'),mode='production'}={}) {
  if(!['production','development'].includes(mode))throw Error(`Unknown content build mode: ${mode}`);
  const {levels,manifest}=readContent(root);
  const validation=validateContent(levels,manifest,{release:mode==='production'});
  if(!validation.ok)throw Error(`Content validation failed: ${JSON.stringify(validation.errors)}`);
  const byId=new Map(levels.map(l=>[l.id,l]));
  // Explicit nested allowlists keep all present/future author fields out of runtime.
  const published=[...manifest.campaign,...manifest.daily].map(id=>{
    const level=byId.get(id);
    return {...pick(level,['id','revision','chapterId','chapter','kind','difficulty','title','intro','layoutVariant']),
      seats:level.seats.map(s=>pick(s,['id','x','y','tags','zone'])),
      adjacency:level.adjacency,
      people:level.people.map(p=>({...pick(p,['id','name','color']),rules:p.rules.map(r=>pick(r,['type','value','person','text']))}))};
  });
  const runtimeManifest={...pick(manifest,['schemaVersion','contentVersion','campaign','daily','dailyCycleAnchorDay']),chapters:manifest.chapters.map(c=>pick(c,['id','title','subtitle','color']))};
  const directory=path.join(root,'src/content/runtime');
  fs.mkdirSync(directory,{recursive:true});
  const files={levels:path.join(directory,'levels.js'),manifest:path.join(directory,'manifest.js')};
  const serialize=value=>`'use strict';\n// Generated by scripts/build-content.js.\nmodule.exports = ${JSON.stringify(value,null,2)};\n`;
  fs.writeFileSync(files.levels,serialize({levels:published}));
  fs.writeFileSync(files.manifest,serialize(runtimeManifest));
  return {levelCount:published.length,contentVersion:manifest.contentVersion,files,report:validation.report};
}
if(require.main===module) {
  try {
    const args=process.argv.slice(2);
    let root,mode='production';
    for(let i=0;i<args.length;i++) {
      if(args[i]==='--root'&&args[i+1])root=path.resolve(args[++i]);
      else if(args[i]==='--mode'&&args[i+1])mode=args[++i];
      else throw Error('Usage: node scripts/build-content.js [--root directory] [--mode production|development]');
    }
    const result=buildContent({root,mode});
    console.log(JSON.stringify({levelCount:result.levelCount,contentVersion:result.contentVersion,files:result.files},null,2));
  }catch(e){console.error(e.message);process.exitCode=1;}
}
module.exports={buildContent};
